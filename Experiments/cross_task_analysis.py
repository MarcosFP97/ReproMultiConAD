"""
Cross-task result analysis for the Pitt -> WLS/Taukadial experiment.

This script intentionally stays narrow: it reads the Excel files generated by
BERT_balanced.py in mode=cross_task and creates the figures/tables needed for
the TFG section. It does not load BERT models, extract embeddings, or perform
token attribution.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd


DEFAULT_RESULTS_DIR = Path("./results/BERT_synthetic_analysis")
DEFAULT_OUTPUT_DIR = Path("./results/cross_task_analysis")
DEFAULT_PATTERN = "bert_balanced_cross_task_binary_disease_status_train-pitt_full_test-*.xlsx"
METRICS = ["Accuracy", "Macro_f1", "Disease_recall", "NoDisease_recall"]
POSITIVE_LABEL = "Disease"
NEGATIVE_LABEL = "NoDisease"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Create final cross-task plots from BERT balanced Excel results.")
    parser.add_argument("--results-dir", type=Path, default=DEFAULT_RESULTS_DIR)
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT_DIR)
    parser.add_argument("--pattern", default=DEFAULT_PATTERN)
    return parser.parse_args()


def require_matplotlib():
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    return plt


def clean_label(value: str) -> str:
    return str(value).replace("true_", "").replace("pred_", "")


def find_result_files(results_dir: Path, pattern: str) -> list[Path]:
    files = sorted(results_dir.glob(pattern))
    if not files:
        raise FileNotFoundError(f"No result files matched {results_dir / pattern}")
    return files


def read_sheet(path: Path, sheet_name: str) -> pd.DataFrame:
    try:
        return pd.read_excel(path, sheet_name=sheet_name)
    except ValueError as exc:
        raise ValueError(f"Missing sheet '{sheet_name}' in {path}") from exc


def read_confusion_matrix(path: Path, sheet_name: str) -> pd.DataFrame:
    try:
        df = pd.read_excel(path, sheet_name=sheet_name, index_col=0)
    except ValueError as exc:
        raise ValueError(f"Missing sheet '{sheet_name}' in {path}") from exc

    df.index = [clean_label(idx) for idx in df.index]
    df.columns = [clean_label(col) for col in df.columns]
    return df


def load_cross_task_results(files: list[Path]) -> tuple[pd.DataFrame, dict[str, dict[str, pd.DataFrame]], pd.DataFrame]:
    summaries = []
    matrices: dict[str, dict[str, pd.DataFrame]] = {}
    predictions = []

    for path in files:
        summary = read_sheet(path, "summary")
        if "Test_dataset" not in summary.columns:
            raise ValueError(f"Missing Test_dataset column in summary sheet: {path}")
        summary["source_file"] = str(path)
        summaries.append(summary)

        dataset = str(summary["Test_dataset"].dropna().iloc[0]).lower()
        matrices[dataset] = {
            "BERT_balanced": read_confusion_matrix(path, "confusion_matrix"),
            "Dummy_most_frequent": read_confusion_matrix(path, "baseline_confusion_matrix"),
        }

        pred = read_sheet(path, "predictions")
        pred["source_file"] = str(path)
        pred["Test_dataset"] = dataset
        predictions.append(pred)

    summary_df = pd.concat(summaries, ignore_index=True)
    predictions_df = pd.concat(predictions, ignore_index=True)
    return summary_df, matrices, predictions_df


def save_summary_tables(summary_df: pd.DataFrame, output_dir: Path) -> None:
    keep_cols = [
        "Estimator",
        "Train_dataset",
        "Test_dataset",
        "Binary_task",
        "Train_rows",
        "Test_rows",
        "Accuracy",
        "Macro_f1",
        "Weighted_f1",
        "Disease_precision",
        "Disease_recall",
        "Disease_f1",
        "Disease_support",
        "NoDisease_precision",
        "NoDisease_recall",
        "NoDisease_f1",
        "NoDisease_support",
    ]
    available = [col for col in keep_cols if col in summary_df.columns]
    tidy = summary_df[available].copy()
    tidy = tidy.sort_values(["Test_dataset", "Estimator"])
    tidy.to_csv(output_dir / "cross_task_summary.csv", index=False)
    tidy.to_excel(output_dir / "cross_task_summary.xlsx", index=False)


def plot_metric_grid(summary_df: pd.DataFrame, output_dir: Path) -> None:
    plt = require_matplotlib()
    datasets = sorted(summary_df["Test_dataset"].astype(str).str.lower().unique())
    estimators = ["BERT_balanced", "Dummy_most_frequent"]
    colors = {"BERT_balanced": "#1f77b4", "Dummy_most_frequent": "#9ca3af"}

    fig, axes = plt.subplots(2, 2, figsize=(11, 7), sharey=True)
    axes = axes.flatten()
    x = np.arange(len(datasets))
    width = 0.36

    for ax, metric in zip(axes, METRICS):
        for idx, estimator in enumerate(estimators):
            values = []
            for dataset in datasets:
                row = summary_df[
                    (summary_df["Test_dataset"].astype(str).str.lower() == dataset)
                    & (summary_df["Estimator"] == estimator)
                ]
                values.append(float(row[metric].iloc[0]) if not row.empty and metric in row.columns else np.nan)
            offset = (idx - 0.5) * width
            ax.bar(x + offset, values, width=width, label=estimator, color=colors[estimator])

        ax.set_title(metric)
        ax.set_xticks(x, labels=[dataset.upper() for dataset in datasets])
        ax.set_ylim(0, 1)
        ax.grid(axis="y", alpha=0.25)

    axes[0].legend(frameon=False, loc="lower right")
    fig.suptitle("Cross-task performance: BERT balanced vs majority baseline")
    fig.tight_layout()
    fig.savefig(output_dir / "metrics_bert_vs_baseline.png", dpi=220)
    plt.close(fig)


def plot_disease_recall(summary_df: pd.DataFrame, output_dir: Path) -> None:
    plt = require_matplotlib()
    datasets = sorted(summary_df["Test_dataset"].astype(str).str.lower().unique())
    estimators = ["BERT_balanced", "Dummy_most_frequent"]
    colors = {"BERT_balanced": "#b91c1c", "Dummy_most_frequent": "#9ca3af"}

    fig, ax = plt.subplots(figsize=(8, 4.8))
    x = np.arange(len(datasets))
    width = 0.36

    for idx, estimator in enumerate(estimators):
        values = []
        for dataset in datasets:
            row = summary_df[
                (summary_df["Test_dataset"].astype(str).str.lower() == dataset)
                & (summary_df["Estimator"] == estimator)
            ]
            values.append(float(row["Disease_recall"].iloc[0]) if not row.empty else np.nan)
        ax.bar(x + (idx - 0.5) * width, values, width=width, label=estimator, color=colors[estimator])

    ax.set_title("Disease recall by target dataset")
    ax.set_ylabel("Recall")
    ax.set_xticks(x, labels=[dataset.upper() for dataset in datasets])
    ax.set_ylim(0, 1)
    ax.grid(axis="y", alpha=0.25)
    ax.legend(frameon=False)
    fig.tight_layout()
    fig.savefig(output_dir / "disease_recall_bert_vs_baseline.png", dpi=220)
    plt.close(fig)


def plot_confusion_matrix_pair(dataset: str, matrices: dict[str, pd.DataFrame], output_dir: Path) -> None:
    plt = require_matplotlib()
    fig, axes = plt.subplots(1, 2, figsize=(10, 4.5))

    for ax, estimator in zip(axes, ["BERT_balanced", "Dummy_most_frequent"]):
        cm = matrices[estimator].copy()
        counts = cm.to_numpy(dtype=float)
        row_sums = counts.sum(axis=1, keepdims=True)
        normalized = np.divide(counts, row_sums, out=np.zeros_like(counts), where=row_sums != 0)

        ax.imshow(normalized, cmap="Blues", vmin=0, vmax=1)
        ax.set_title(estimator)
        ax.set_xticks(range(len(cm.columns)), labels=cm.columns, rotation=30, ha="right")
        ax.set_yticks(range(len(cm.index)), labels=cm.index)
        ax.set_xlabel("Predicted")
        ax.set_ylabel("True")

        for i in range(counts.shape[0]):
            for j in range(counts.shape[1]):
                ax.text(j, i, f"{int(counts[i, j])}\n{normalized[i, j]:.0%}", ha="center", va="center")

    fig.suptitle(f"Confusion matrices on {dataset.upper()}")
    fig.tight_layout()
    fig.savefig(output_dir / f"confusion_{dataset}.png", dpi=220)
    plt.close(fig)


def classify_error_type(y_true: str, y_pred: str) -> str:
    if y_true == POSITIVE_LABEL and y_pred == POSITIVE_LABEL:
        return "TP_Disease"
    if y_true == POSITIVE_LABEL and y_pred != POSITIVE_LABEL:
        return "FN_Disease"
    if y_true != POSITIVE_LABEL and y_pred == POSITIVE_LABEL:
        return "FP_Disease"
    return "TN_NoDisease"


def build_error_type_table(predictions_df: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for _, row in predictions_df.iterrows():
        dataset = str(row["Test_dataset"]).lower()
        true_label = str(row["true_label"])
        rows.append({
            "Test_dataset": dataset,
            "Estimator": "BERT_balanced",
            "error_type": classify_error_type(true_label, str(row["pred_label"])),
        })
        if "baseline_pred_label" in predictions_df.columns:
            rows.append({
                "Test_dataset": dataset,
                "Estimator": "Dummy_most_frequent",
                "error_type": classify_error_type(true_label, str(row["baseline_pred_label"])),
            })

    table = pd.DataFrame(rows)
    return (
        table.groupby(["Test_dataset", "Estimator", "error_type"])
        .size()
        .reset_index(name="count")
    )


def plot_error_types(predictions_df: pd.DataFrame, output_dir: Path) -> None:
    plt = require_matplotlib()
    table = build_error_type_table(predictions_df)
    table.to_csv(output_dir / "error_types_by_dataset.csv", index=False)

    error_order = ["TP_Disease", "FN_Disease", "FP_Disease", "TN_NoDisease"]
    colors = {
        "TP_Disease": "#15803d",
        "FN_Disease": "#dc2626",
        "FP_Disease": "#f97316",
        "TN_NoDisease": "#2563eb",
    }
    groups = table[["Test_dataset", "Estimator"]].drop_duplicates().sort_values(["Test_dataset", "Estimator"])
    x = np.arange(len(groups))

    fig, ax = plt.subplots(figsize=(11, 5.5))
    bottom = np.zeros(len(groups))
    labels = [f"{row.Test_dataset.upper()}\n{row.Estimator.replace('_', ' ')}" for row in groups.itertuples()]

    for error_type in error_order:
        values = []
        for row in groups.itertuples():
            match = table[
                (table["Test_dataset"] == row.Test_dataset)
                & (table["Estimator"] == row.Estimator)
                & (table["error_type"] == error_type)
            ]
            values.append(int(match["count"].iloc[0]) if not match.empty else 0)
        ax.bar(x, values, bottom=bottom, label=error_type, color=colors[error_type])
        bottom += np.array(values)

    ax.set_title("Cross-task error types by dataset")
    ax.set_ylabel("Number of samples")
    ax.set_xticks(x, labels=labels)
    ax.legend(frameon=False, ncol=2)
    ax.grid(axis="y", alpha=0.2)
    fig.tight_layout()
    fig.savefig(output_dir / "error_types_by_dataset.png", dpi=220)
    plt.close(fig)


def plot_confidence(predictions_df: pd.DataFrame, output_dir: Path) -> None:
    if "confidence" not in predictions_df.columns:
        return

    plt = require_matplotlib()
    correct_series = predictions_df["correct"]
    if correct_series.dtype == object:
        correct_series = correct_series.astype(str).str.lower().isin({"true", "1", "yes"})
    else:
        correct_series = correct_series.astype(bool)

    data = []
    labels = []
    for dataset in sorted(predictions_df["Test_dataset"].astype(str).str.lower().unique()):
        for correct_value, label in [(True, "correct"), (False, "incorrect")]:
            values = predictions_df[
                (predictions_df["Test_dataset"].astype(str).str.lower() == dataset)
                & (correct_series == correct_value)
            ]["confidence"].dropna()
            if not values.empty:
                data.append(values.to_numpy(dtype=float))
                labels.append(f"{dataset.upper()}\n{label}")

    if not data:
        return

    fig, ax = plt.subplots(figsize=(9, 5))
    ax.boxplot(data, labels=labels, showfliers=False)
    ax.set_title("BERT confidence for correct vs incorrect predictions")
    ax.set_ylabel("Confidence")
    ax.set_ylim(0, 1)
    ax.grid(axis="y", alpha=0.25)
    fig.tight_layout()
    fig.savefig(output_dir / "confidence_correct_vs_incorrect.png", dpi=220)
    plt.close(fig)


def write_markdown_summary(summary_df: pd.DataFrame, output_dir: Path) -> None:
    metrics_df = summary_df[
        ["Estimator", "Test_dataset", "Accuracy", "Macro_f1", "Disease_recall", "NoDisease_recall"]
    ].sort_values(["Test_dataset", "Estimator"])
    table_lines = [
        "| Estimator | Test dataset | Accuracy | Macro-F1 | Disease recall | NoDisease recall |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for row in metrics_df.itertuples(index=False):
        table_lines.append(
            f"| {row.Estimator} | {row.Test_dataset} | "
            f"{row.Accuracy:.4f} | {row.Macro_f1:.4f} | "
            f"{row.Disease_recall:.4f} | {row.NoDisease_recall:.4f} |"
        )

    lines = [
        "# Cross-task analysis summary",
        "",
        "Task: Pitt full training set, mapped as `HC -> NoDisease` and `MCI/Dementia -> Disease`.",
        "",
        "## Metrics",
        "",
        *table_lines,
        "",
        "## Generated Figures",
        "",
        "- `metrics_bert_vs_baseline.png`",
        "- `disease_recall_bert_vs_baseline.png`",
        "- `confusion_wls.png` and `confusion_taukadial.png` when those datasets are present",
        "- `error_types_by_dataset.png`",
        "- `confidence_correct_vs_incorrect.png`",
        "",
    ]
    (output_dir / "summary.md").write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    args = parse_args()
    args.output_dir.mkdir(parents=True, exist_ok=True)

    files = find_result_files(args.results_dir, args.pattern)
    summary_df, matrices, predictions_df = load_cross_task_results(files)

    save_summary_tables(summary_df, args.output_dir)
    plot_metric_grid(summary_df, args.output_dir)
    plot_disease_recall(summary_df, args.output_dir)

    for dataset, dataset_matrices in matrices.items():
        plot_confusion_matrix_pair(dataset, dataset_matrices, args.output_dir)

    plot_error_types(predictions_df, args.output_dir)
    plot_confidence(predictions_df, args.output_dir)
    write_markdown_summary(summary_df, args.output_dir)

    print(f"[OK] Cross-task analysis written to: {args.output_dir}")


if __name__ == "__main__":
    main()
